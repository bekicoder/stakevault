import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const contracts = [
  ["StakingVault", "stakingVaultAbi"],
  ["StakeToken", "stakeTokenAbi"],
];

mkdirSync("src/abi", { recursive: true });
for (const [name, exportName] of contracts) {
  const path = `../contracts/artifacts/contracts/${name}.sol/${name}.json`;
  const { abi } = JSON.parse(readFileSync(path, "utf8"));
  writeFileSync(
    `src/abi/${name}.ts`,
    `// Generated by scripts/sync-abi.mjs. Do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  console.log(`synced ${name}`);
}
